CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS money_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(150) NOT NULL,
    initial_balance NUMERIC(19, 2) NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS budget_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(150) NOT NULL,
    monthly_limit NUMERIC(19, 2) NOT NULL CHECK (monthly_limit >= 0)
);

CREATE TABLE IF NOT EXISTS savings_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    account_id BIGINT NOT NULL REFERENCES money_accounts(id) ON DELETE CASCADE,
    name VARCHAR(150) NOT NULL,
    target_amount NUMERIC(19, 2) NOT NULL CHECK (target_amount > 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('ACTIVE', 'PAUSED', 'COMPLETED'))
);

CREATE TABLE IF NOT EXISTS financial_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES money_accounts(id) ON DELETE CASCADE,
    category_id BIGINT REFERENCES budget_categories(id) ON DELETE CASCADE,
    goal_id BIGINT REFERENCES savings_goals(id) ON DELETE CASCADE,
    amount NUMERIC(19, 2) NOT NULL CHECK (amount > 0),
    type VARCHAR(20) NOT NULL CHECK (type IN ('INCOME', 'EXPENSE', 'CONTRIBUTION')),
    occurred_at TIMESTAMP NOT NULL,
    posted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT transaction_association CHECK (
        (type = 'INCOME' AND category_id IS NULL AND goal_id IS NULL)
        OR (type = 'EXPENSE' AND category_id IS NOT NULL AND goal_id IS NULL)
        OR (type = 'CONTRIBUTION' AND category_id IS NULL AND goal_id IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_transactions_account ON financial_transactions(account_id);
CREATE INDEX IF NOT EXISTS idx_transactions_goal ON financial_transactions(goal_id);
CREATE INDEX IF NOT EXISTS idx_transactions_category ON financial_transactions(category_id);
